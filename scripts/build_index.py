"""Regenerate docs/LEDGER.md and docs/BACKLOG.md from docs/ledger/*.yaml and docs/backlog/*.md.

Never hand-edit the generated tables. Run: python3 scripts/build_index.py  (add --check to fail if stale)
Also validates every ledger entry has the required fields and a known verdict.
"""
import glob
import os
import sys

import yaml

RepoRoot = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
Required = ["id", "title", "family", "hypothesis", "coverage", "detector", "control", "null", "result",
            "skips_handled", "source", "date", "artifacts"]
Verdicts = {"negative", "positive", "inconclusive"}
Header = "<!-- GENERATED by scripts/build_index.py; do not edit by hand -->\n"


def Cell(Value, Limit=70):
    Text = " ".join(str(Value).split()).replace("|", "/")
    return Text if len(Text) <= Limit else Text[: Limit - 1] + "…"


def ReadFrontMatter(Path):
    with open(Path, encoding="utf-8") as Handle:
        Text = Handle.read()
    if not Text.startswith("---"):
        raise ValueError(f"{Path}: missing front matter")
    return yaml.safe_load(Text.split("---", 2)[1])


def LedgerTable(Problems):
    Rows = []
    SeenIds = set()
    for Path in sorted(glob.glob(os.path.join(RepoRoot, "docs", "ledger", "E*.yaml"))):
        with open(Path, encoding="utf-8") as Handle:
            Entry = yaml.safe_load(Handle)
        Missing = [Key for Key in Required if Key not in Entry]
        if Missing:
            Problems.append(f"{os.path.basename(Path)}: missing {Missing}")
            continue
        Verdict = Entry["result"].get("verdict")
        if Verdict not in Verdicts:
            Problems.append(f"{os.path.basename(Path)}: bad verdict {Verdict!r}")
        if not os.path.basename(Path).startswith(Entry["id"] + "-"):
            Problems.append(f"{os.path.basename(Path)}: id {Entry['id']} does not match file name")
        if Entry["id"] in SeenIds:
            Problems.append(f"{os.path.basename(Path)}: duplicate id {Entry['id']} (renumber the newer file)")
        SeenIds.add(Entry["id"])
        Control = Entry["control"].get("score")
        Ceiling = Entry["null"].get("ceiling")
        Flag = "" if str(Control) != "not reported" else " ⚠"
        Rows.append(f"| [{Entry['id']}](ledger/{os.path.basename(Path)}) | {Cell(Entry['title'], 60)} | {Entry['family']} | "
                    f"{Cell(Control, 30)}{Flag} | {Cell(Ceiling, 30)} | {Cell(Entry['result'].get('best'), 45)} | {Verdict} | "
                    f"{Cell(Entry['skips_handled'], 20)} | {Cell(Entry['source'], 30)} |")
    Families = sorted({Row.split(" | ")[2] for Row in Rows})
    return (Header + "# Ledger\n\n"
            f"{len(Rows)} experiments. ⚠ = no positive-control score recorded (external, or lab run without a plant): not lab-verified.\n"
            f"Families: {', '.join(Families)}.\n\n"
            "| id | title | family | control | null ceiling | best | verdict | skips | source |\n"
            "| --- | --- | --- | --- | --- | --- | --- | --- | --- |\n" + "\n".join(Rows) + "\n")


def BacklogTable(Problems):
    Items = []
    for Path in sorted(glob.glob(os.path.join(RepoRoot, "docs", "backlog", "B*.md"))):
        try:
            Meta = ReadFrontMatter(Path)
        except ValueError as Error:
            Problems.append(str(Error))
            continue
        if Meta.get("status") not in {"open", "claimed", "done"}:
            Problems.append(f"{os.path.basename(Path)}: bad status {Meta.get('status')!r}")
        Items.append((Meta.get("status") == "done", Meta.get("rank", 99), Meta, os.path.basename(Path)))
    Items.sort(key=lambda Item: (Item[0], Item[1]))
    Rows = [f"| {Meta.get('rank')} | [{Meta['id']}](backlog/{Name}) | {Cell(Meta.get('title'), 60)} | {Meta.get('status')} | "
            f"{Meta.get('claimed_by') or ''} | {', '.join(Meta.get('ledger') or [])} |" for _, _, Meta, Name in Items]
    return (Header + "# Backlog\n\nOpen and claimed items first, by rank. Claim an item by editing its own file.\n\n"
            "| rank | id | title | status | claimed_by | ledger |\n| --- | --- | --- | --- | --- | --- |\n"
            + "\n".join(Rows) + "\n")


def Main():
    Problems = []
    Outputs = {os.path.join(RepoRoot, "docs", "LEDGER.md"): LedgerTable(Problems),
               os.path.join(RepoRoot, "docs", "BACKLOG.md"): BacklogTable(Problems)}
    if Problems:
        print("PROBLEMS:\n  " + "\n  ".join(Problems))
        return 1
    Stale = []
    for Path, Text in Outputs.items():
        Old = open(Path, encoding="utf-8").read() if os.path.exists(Path) else ""
        if Old != Text:
            Stale.append(os.path.relpath(Path, RepoRoot))
            if "--check" not in sys.argv:
                with open(Path, "w", encoding="utf-8") as Handle:
                    Handle.write(Text)
    if "--check" in sys.argv and Stale:
        print("stale:", Stale, "- run python3 scripts/build_index.py")
        return 1
    print(f"index ok ({'updated ' + ', '.join(Stale) if Stale else 'no changes'})")
    return 0


if __name__ == "__main__":
    sys.exit(Main())
